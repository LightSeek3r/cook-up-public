/**
 * `GENERIC_PAIRS`, transitively closed — and it is this, not the curated list,
 * that must be seeded into `ingredient_generic_of`.
 *
 * `src/lib/match.ts` joins that table exactly **once** per recipe ingredient
 * (`igo.specific_id = ri.ingredient_id` against `igo.generic_id IN (selection)`).
 * One join walks one hop, so chains have to be pre-flattened: the curated list
 * holds `sugar -> brown_sugar` and `brown_sugar -> dark_brown_sugar`, but with no
 * explicit `sugar -> dark_brown_sugar` row, selecting "sugar" does not satisfy a
 * recipe calling for dark brown sugar.
 *
 * That was a live bug before it was a hypothesis: eight recipes stopped matching
 * `sugar` the moment their line resolved to `dark_brown_sugar` instead of bare
 * `sugar`. Other chains the curated list leaves broken the same way include
 * `egg -> meringue` (via `egg_white`), `broth -> stock_cube` (via
 * `dehydrated_broth`) and `grape -> sultana_raisin` (via `raisin`) — all of which
 * predate the specificity work; it only made them observable.
 *
 * Derived rather than written out above so the curated data stays short and
 * reviewable: one new curated pair propagates on its own, and transitivity can't
 * drift out of sync with it. Safe by construction — if `(a,b)` and `(b,c)` are
 * both "selecting a satisfies b" relations then so is `(a,c)`, so closure adds no
 * relation that wasn't already implied. Currently expands 491 pairs to 533.
 */
export const GENERIC_PAIRS_CLOSED = (() => {
	const specificsOf = new Map();
	for (const [generic, specific] of GENERIC_PAIRS) {
		if (!specificsOf.has(generic)) specificsOf.set(generic, new Set());
		specificsOf.get(generic).add(specific);
	}
	// Iterate to a fixed point: chains can be longer than two hops.
	for (let grew = true; grew; ) {
		grew = false;
		for (const [generic, specifics] of specificsOf) {
			for (const specific of [...specifics]) {
				for (const deeper of specificsOf.get(specific) ?? []) {
					// Guard the self-pair: a cycle in the curated data would otherwise
					// hand `ingredient_generic_of` a row claiming an ingredient is its
					// own generic.
					if (deeper === generic || specifics.has(deeper)) continue;
					specifics.add(deeper);
					grew = true;
				}
			}
		}
	}
	return [...specificsOf]
		.flatMap(([generic, specifics]) => [...specifics].map((specific) => [generic, specific]))
		.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
})();
