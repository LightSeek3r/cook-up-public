/**
 * Curated `[generic, specific]` pairs: selecting the generic ingredient also
 * satisfies a recipe's need for the specific one (never the reverse) — see
 * `src/lib/match.ts`'s `ingredient_generic_of` table, which this list seeds.
 *
 * Deliberately NOT "trust the taxonomy's parent/child DAG generally" — that
 * was tried and rejected. Two real problems with it, confirmed against the
 * real Open Food Facts file:
 *
 * 1. Many taxonomy parents are whole food-group CATEGORIES, not a specific
 *    food with named variants — `spice` parents cinnamon/ginger/turmeric/
 *    nutmeg, `cheese` parents mozzarella/blue cheese/cream cheese, `sauce`
 *    parents ketchup/soy sauce/mayonnaise. Selecting "spice" should never
 *    satisfy a recipe that specifically needs cinnamon. Every generic key
 *    below is a specific food (onion, sugar, egg, ...), never a category
 *    anchor — the excluded anchors were: alcohol, berries, cereal, cheese,
 *    coating, dough, fish, fruit, herb, legume, meat, mixed_spices, nut,
 *    oil_and_fat, poultry, salad, sauce, spice, vegetable.
 * 2. The DAG itself isn't fully reliable for this purpose: `allspice`'s
 *    declared taxonomy parent is `chili_pepper` (its old English name is
 *    "Jamaica pepper" — a lexical accident, not a real relationship).
 *    Confirmed absent from the list below on purpose.
 *
 * Everything else — different varieties of the same food (onion, sugar,
 * vinegar, oils, wine), concentrated/dehydrated forms (tomato puree, onion
 * powder), and prepared components (meringue from egg white) — made the cut.
 * That's a deliberate product decision (discovery over strict nutritional
 * fidelity), not an oversight: see tasks/todo.md for the full case-by-case
 * reasoning this list was built from.
 *
 * Regenerate by re-deriving from the taxonomy DAG and re-applying the same
 * exclusions (see `tasks/todo.md`) — don't hand-edit piecemeal without
 * re-checking both exclusion rules still hold for the new entry.
 *
 * CLOSURE INVARIANT — this list is load-bearing for anything that makes
 * ingredient matching *more specific*. When stage 03 started resolving
 * `black_pepper` where it used to resolve `pepper`, every such refinement
 * needed a covering `[generic, specific]` edge, or the recipe would silently
 * stop matching for a user who selected the generic — a regression invisible to
 * every test, since each corpus is internally consistent. So after any change to
 * how keys are resolved: diff the old and new `recipe_ingredients.jsonl`, and
 * for every line that moved from `G` to a more specific `S`, either add a
 * `(G, S)` edge here or be able to say why not.
 *
 * 280 of the 521 entries below came from exactly that pass, run twice — once for
 * the specificity change and again for the unmatched-line recovery, which
 * refined another 304 lines and needed 29 more edges (`tomato` ->
 * `crushed_tomato` and friends). Two parts each time:
 *
 *  - 229 where `S` is a taxonomy *descendant* of `G` (`pepper` ->
 *    `black_pepper`). Mechanical and safe to derive in bulk.
 *  - 21 where it isn't, and only reading them one at a time works. `lemon` ->
 *    `lemon_juice` and `dehydrated_broth` -> `stock_cube` are real generic
 *    relations that OFF's DAG simply doesn't encode, so a descendant-only
 *    closure misses them — that showed up as 79 selections returning fewer
 *    recipes than before, which is how the gap was found rather than reasoned
 *    about. The same diff also contained `tomato` -> `bell_pepper` and `beef` ->
 *    `chicken_breast`, where the *old* key was merely wrong and there is no
 *    relation to preserve; those were left out.
 *
 * Also left out: 21 descendant refinements whose generic was a category anchor
 * (`cheese` -> `cheddar`), per rule 1. That deliberately costs a little
 * discoverability — selecting "cheese" no longer finds a recipe that names goat
 * cheese specifically — and is the documented trade, not an oversight.
 */
