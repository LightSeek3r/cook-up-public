let failed = false;
for (const [lang, values] of Object.entries(VALUES)) {
	if (values.length !== KEYS.length) {
		console.error(`${lang}: expected ${KEYS.length} values, got ${values.length}`);
		failed = true;
		continue;
	}
	if (values.some((value) => !value.trim())) {
		console.error(`${lang}: blank value`);
		failed = true;
	}
	if (values[KEYS.indexOf('glossary.count')].split('{n}').length !== 2) {
		console.error(`${lang}: glossary.count must contain exactly one {n}`);
		failed = true;
	}
}
if (failed) process.exit(1);

for (const [lang, values] of Object.entries(VALUES)) {
	const file = path.join(DIR, `${lang}.json`);
	const raw = readFileSync(file, 'utf8');
	const bom = raw.charCodeAt(0) === 0xfeff ? '\uFEFF' : '';
	const obj = JSON.parse(raw.replace(/^\uFEFF/, ''));

	KEYS.forEach((key, i) => (obj[key] = values[i]));

	writeFileSync(file, bom + JSON.stringify(obj, null, 2) + '\n', 'utf8');
	console.log(`${lang}: ${Object.keys(obj).length} keys`);
}
